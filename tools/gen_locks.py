"""Generate the lock data (domain/Locks.kt) and the reference sentences for the unit tests (test/.../ReferenceData.kt)
from the factory design package (apps/luban-lock/design-package.json, locks[]). The data is the puzzle itself, so it is
never typed by hand.

  python -X utf8 tools/gen_locks.py [path/to/design-package.json]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DP = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(HERE), "spatial-app-factory", "apps", "luban-lock", "design-package.json")
MAIN = os.path.join(HERE, "app", "src", "main", "java", "io", "embodit", "lubanlock", "domain", "Locks.kt")
TEST = os.path.join(HERE, "app", "src", "test", "java", "io", "embodit", "lubanlock", "domain", "ReferenceData.kt")

WOOD = {"beech": "BEECH", "cherry": "CHERRY", "walnut": "WALNUT"}


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def v(c):
    return "V3i(%d, %d, %d)" % tuple(c)


def main():
    d = json.load(open(DP, encoding="utf-8"))
    out = [
        "package io.embodit.lubanlock.domain",
        "",
        "// GENERATED by tools/gen_locks.py from the design package locks[] — do not edit by hand.",
        "",
        "/** The three six-piece locks of v1 (design locks[]; solver-verified by the product station 2026-11-05). */",
        "object Locks {",
        "    val ALL: List<Lock> = listOf(",
    ]
    for lk in d["locks"]:
        notches = ", ".join("%d to listOf(%s)" % (p["id"], ", ".join(v(c) for c in p["notches"])) for p in lk["pieces"])
        out.append("        Lock(")
        out.append("            id = %s, nameZh = %s, nameEn = %s," % (kstr(lk["id"]), kstr(lk["nameZh"]), kstr(lk["nameEn"])))
        out.append("            taglineZh = %s, taglineEn = %s," % (kstr(lk["taglineZh"]), kstr(lk["taglineEn"])))
        out.append("            wood = Wood.%s, stars = %d, minMoves = %d," % (WOOD[lk["woodEn"]], lk["difficulty"], lk["minTakeApartMoves"]))
        out.append("            holes = setOf(%s)," % ", ".join(v(c) for c in lk["holes"]))
        out.append("            notches = mapOf(%s)," % notches)
        out.append("        ),")
    out += ["    )", "", "    fun byId(id: String): Lock? = ALL.firstOrNull { it.id == id }", "}", ""]
    open(MAIN, "w", encoding="utf-8", newline="\n").write("\n".join(out))

    t = [
        "package io.embodit.lubanlock.domain",
        "",
        "// GENERATED by tools/gen_locks.py from the design package locks[] — do not edit by hand.",
        "",
        "/** One reference step of the canonical solution: the move and the sentence the templates must produce (lock not turned). */",
        "data class RefStep(val piece: Int, val dir: String, val dist: String, val kind: String, val freedBy: Int?, val next: Int?, val mustBeat: List<Int>, val zh: String, val en: String)",
        "",
        "object ReferenceData {",
        "    val TAKE_APART: Map<String, List<RefStep>> = mapOf(",
    ]

    def step(s, insert_field=False):
        dist = "out" if s.get("dist") == "out" or (insert_field and s.get("insert")) else str(s.get("dist"))
        nxt = s.get("next", s.get("nextInsert"))
        return "RefStep(%d, %s, %s, %s, %s, %s, listOf(%s), %s, %s)" % (
            s["piece"], kstr(s["dir"]), kstr(dist), kstr(s["kind"]),
            "null" if s.get("freedBy") is None else s["freedBy"],
            "null" if nxt is None else nxt,
            ", ".join(str(x) for x in s.get("mustBeat", [])), kstr(s["zh"]), kstr(s["en"]))

    for lk in d["locks"]:
        t.append("        %s to listOf(" % kstr(lk["id"]))
        t += ["            %s," % step(s) for s in lk["takeApart"]]
        t.append("        ),")
    t += ["    )", "", "    val PUT_BACK: Map<String, List<RefStep>> = mapOf("]
    for lk in d["locks"]:
        t.append("        %s to listOf(" % kstr(lk["id"]))
        t += ["            %s," % step(s, True) for s in lk["putBack"]]
        t.append("        ),")
    t += ["    )", "", "    /** verified.reachableStatesCap1 / hintBfsFromStart.unitMovesToFirstRemoval / maxExitFarEndUnits */"]
    t.append("    val REACHABLE = mapOf(%s)" % ", ".join("%s to %d" % (kstr(lk["id"]), lk["verified"]["reachableStatesCap1"]) for lk in d["locks"]))
    t.append("    val FIRST_REMOVAL = mapOf(%s)" % ", ".join("%s to %d" % (kstr(lk["id"]), lk["verified"]["hintBfsFromStart"]["unitMovesToFirstRemoval"]) for lk in d["locks"]))
    t += ["}", ""]
    os.makedirs(os.path.dirname(TEST), exist_ok=True)
    open(TEST, "w", encoding="utf-8", newline="\n").write("\n".join(t))
    print("wrote", MAIN, "and", TEST)


if __name__ == "__main__":
    main()
